const IMAGES_PRODUITS = Object.freeze(Object.fromEntries(
  Object.entries(VISUELS).map(([id, chemin]) => [id, `https://trajectoiredroit.com/${chemin}`])
));

// Ajoute les images après les variantes cadeau et échéances pour les conserver
// dans tous les parcours, sans changer les autres paramètres du paiement.
function avecImagesProduits(params) {
  const ids = String(params.metadata && params.metadata.produitIds || "").split(",");
  return {
    ...params,
    line_items: params.line_items.map((ligne, index) => {
      const image = IMAGES_PRODUITS[ids[index]];
      if (!image || !ligne.price_data || !ligne.price_data.product_data) return ligne;
      return {
        ...ligne,
        price_data: {
          ...ligne.price_data,
          product_data: { ...ligne.price_data.product_data, images: [image] },
        },
      };
    }),
  };
}

module.exports = { IMAGES_PRODUITS, avecImagesProduits };
